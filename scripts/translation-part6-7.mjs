const data = JSON.parse(fs.readFileSync(source, "utf8"));
const failures = [];
let groupCount = 0;
let itemCount = 0;

for (const part of data.parts) {
  if (part.part !== 6 && part.part !== 7) continue;
  for (const group of part.questions) {
    const passageTranslation = passageTranslations[String(group.id)];
    if (!passageTranslation) failures.push(`missing passage translation for ${group.id}`);
    else {
      group.passage_translation = passageTranslation;
      group.content_translation = passageTranslation;
      groupCount += 1;
    }

    for (const item of group.items ?? []) {
      const translated = itemTranslations[item.id];
      if (!translated) {
        failures.push(`missing item translation for ${item.id}`);
        continue;
      }
      if (item.question) {
        if (!translated.question) failures.push(`missing question translation for ${item.id}`);
        else item.question_translation = translated.question;
      }
      if (!Array.isArray(translated.choices) || translated.choices.length !== item.choices.length) {
        failures.push(`choice count mismatch for ${item.id}`);
      } else {
        item.choice_translations = translated.choices.map((choice, index) => `${"ABCD"[index]}：${choice}`);
      }
      itemCount += 1;
    }
  }
}

if (failures.length) {
  throw new Error(`Part 6–7 translation map is incomplete:\n${failures.join("\n")}`);
}

fs.writeFileSync(source, `${JSON.stringify(data, null, 2)}\n`);
console.log(`Updated ${groupCount} Part 6–7 passages and ${itemCount} items in ${source.pathname}`);
